#!/usr/bin/env python3
"""Build props/catalog.json and props/<pack>/0_preview.jpg from every props/<pack>/*.glb.

  .venv/bin/python scripts/props_catalog.py            # catalog + preview
  .venv/bin/python scripts/props_catalog.py --no-preview

catalog.json: per pack, per model: size [x, y, z] in model units, and a ready
"snippet" for short.json. preview.jpg: one labelled tile per model (rendered by
the stage, so it shows the real look with outline and light).
"""
import json, os, struct, subprocess, sys, glob

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PROPS = os.path.join(ROOT, 'props')
RENDER = os.path.join(ROOT, '.claude/skills/ricksclips-short-style/scripts/stage/render.mjs')


def glb_size(path):
    b = open(path, 'rb').read()
    n = struct.unpack('<I', b[12:16])[0]
    j = json.loads(b[20:20 + n])
    mn, mx = [1e9] * 3, [-1e9] * 3
    for m in j['meshes']:
        for p in m['primitives']:
            a = j['accessors'][p['attributes']['POSITION']]
            mn = [min(x, y) for x, y in zip(mn, a['min'])]
            mx = [max(x, y) for x, y in zip(mx, a['max'])]
    return [round(y - x, 2) for x, y in zip(mn, mx)]


def main():
    catalog = {'_note': 'Generated by scripts/props_catalog.py. size = model units (hero is 1.8 high); use "scale" or "height" in short.json.', 'packs': {}}
    items = []
    for pack in sorted(os.listdir(PROPS)):
        pd = os.path.join(PROPS, pack)
        if not os.path.isdir(pd):
            continue
        models = {}
        for f in sorted(glob.glob(pd + '/*.glb')):
            name = os.path.basename(f)[:-4]
            size = glb_size(f)
            rel = f'props/{pack}/{name}.glb'
            models[name] = {'file': rel, 'size': size}
            items.append((pack, name, rel, size))
        catalog['packs'][pack] = models
    json.dump(catalog, open(os.path.join(PROPS, 'catalog.json'), 'w'), indent=1)
    print(f'catalog.json: {len(items)} models in {len(catalog["packs"])} pack(s)')
    if '--no-preview' in sys.argv:
        return
    only = [a for a in sys.argv[1:] if not a.startswith('--')]
    for pack_name in catalog['packs']:
        if only and pack_name not in only:
            continue
        preview(pack_name, [i for i in items if i[0] == pack_name])


PAGE = 40  # models per preview image


def preview(pack_name, items):
    """Write props/<pack>/0_preview.jpg (+ 0_preview_2.jpg ... for big packs)."""
    from PIL import Image, ImageDraw
    pd = os.path.join(PROPS, pack_name)
    for old in glob.glob(os.path.join(pd, '0_preview*.jpg')):
        os.remove(old)
    for page, start in enumerate(range(0, len(items), PAGE), 1):
        chunk = items[start:start + PAGE]
        props, shots = [], []
        for i, (pack, name, rel, size) in enumerate(chunk):
            x = i * 40
            big = max(size)
            sc = 2.0 / big if big > 0 else 1  # normalise every model to ~2 units, preview only
            props.append({'type': 'box', 'pos': [x, 0.01, 0], 'size': [4, 0.02, 4], 'color': '#c9b9a0'})
            props.append({'type': 'model', 'file': rel, 'pos': [x, 0.02, 0], 'scale': sc, 'rotY': -25})
            shots.append({'start': i * 1.5, 'anchor': [x, 0.8, 0], 'distance': 8, 'yaw': 0, 'pitch': 12, 'out': 'cut'})
        spec = {'fps': 30, 'moods': {'day': {'sun': {'azimuth': 35, 'elevation': 50, 'color': '#ffe0b5', 'intensity': 2.4}, 'sky': {'top': '#5f86d8', 'horizon': '#f2b98a'}, 'fill': {'sky': '#8ea2ff', 'ground': '#7a4a7c', 'intensity': 1.2}}}, 'lighting': [{'t': 0, 'mood': 'day', 'fade': 0.01}], 'ground': {'color': '#8cbf5a'}, 'ink': {'set': 4},
                'characters': [], 'props': props, 'shots': shots, 'actions': [], 'end': len(chunk) * 1.5}
        pj = os.path.join(ROOT, '.preview_props.json')
        json.dump(spec, open(pj, 'w'))
        subprocess.run(['node', RENDER, pj, os.path.join(ROOT, '.preview_props.mp4'), '--stills', '--scale', '0.4', '--no-audio'], cwd=ROOT, check=True, stdout=subprocess.DEVNULL)
        still_dir = os.path.join(ROOT, '.preview_props_stills')
        tiles = []
        for i, (pack, name, rel, size) in enumerate(chunk):
            im = Image.open(os.path.join(still_dir, f'shot{i:02d}_b.jpg')).convert('RGB')
            w, h = im.size
            im = im.crop((0, int(h * 0.2), w, int(h * 0.8))).resize((int(w * 0.6), int(h * 0.6 * 0.6)))
            d = ImageDraw.Draw(im)
            d.rectangle((0, 0, im.width, 30), fill=(30, 25, 40))
            d.text((5, 3), name, fill=(255, 255, 255))
            d.text((5, 16), ' x '.join(map(str, size)), fill=(200, 200, 220))
            tiles.append(im)
        cols = 8 if len(items) > 25 else 5
        tw, th = tiles[0].size
        rows = (len(tiles) + cols - 1) // cols
        sheet = Image.new('RGB', (cols * tw, rows * th), (30, 25, 40))
        for i, t in enumerate(tiles):
            sheet.paste(t, ((i % cols) * tw, (i // cols) * th))
        fn = '0_preview.jpg' if page == 1 else f'0_preview_{page}.jpg'
        sheet.save(os.path.join(pd, fn), quality=88)
        print(f'props/{pack_name}/{fn} written ({len(chunk)} models)')
        for f in (pj, os.path.join(ROOT, '.preview_props.mp4')):
            if os.path.exists(f):
                os.remove(f)
        subprocess.run(['rm', '-rf', still_dir])


if __name__ == '__main__':
    main()
